    "",
    "    model = build_model(model_name, num_classes=NUM_CLASSES).to(device)",
    "    scaler = torch.amp.GradScaler('cuda') if device.type == 'cuda' else None",
    "",
    "    best_val_loss = float('inf')",
    "    best_val_acc = 0.0",
    "    start_epoch = 1",
    "    history = []",
    "",
